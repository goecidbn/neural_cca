"""Synthetic spike-train and waveform generators.

This module is the single source of truth for the synthetic neural
data used by the example notebooks under ``examples/`` and by the
test suite under ``tests/``.  Before this module existed, every
notebook copy-pasted the same ~115 lines of Poisson-spike-and-
Gaussian-waveform setup, and ``tests/conftest.py`` carried its own
slightly different copy — three or four implementations of the same
idea, drifting out of sync any time someone touched one of them.

Public helpers
--------------
:func:`poisson_train`
    Bin-wise inhomogeneous Poisson process with an absolute
    refractory period.  Used by the notebooks to build per-trial
    spike trains with a tuning-curve-shaped rate profile.

:func:`make_tuned_spikes`
    Single Gaussian-tuned cluster — produces ``(spike_times, trials,
    angles, unique_angles)`` for one neuron with a chosen preferred
    direction.  Used by the tuning / statistics test fixtures.  Uses
    the simple per-trial ``rng.poisson`` + ``rng.uniform`` recipe so
    seeded test assertions stay stable.

:func:`make_two_unit_demo`
    Two-cluster "notebook demo" dataset — one orientation-indifferent
    unit and one orientation-selective unit, generated by
    :func:`poisson_train` with a bin-wise refractory period, plus
    Gaussian waveform templates.  Returns a :class:`TwoUnitDemo`
    NamedTuple containing every array the four example notebooks
    used to build inline (spike times, trials, angles, waveforms,
    ground-truth labels, plus a fully-loaded ``SortingData``).

Layering
--------
Notebooks ship through ``examples/`` and end-users open them
directly; they cannot rely on ``tests/conftest.py`` because
``tests/`` is not in the installed wheel
(``[tool.hatch.build.targets.wheel] packages = ["neural_cca"]``).
This module lives inside ``neural_cca/`` so both notebooks and the
test fixtures import from the same place.
"""

from __future__ import annotations

from typing import NamedTuple

import numpy as np
import numpy.typing as npt

from ._utils import make_rng, steps2degree
from .sorting.containers import SortingData
from .sorting.io_util import load_from_arrays

__all__ = [
    "poisson_train",
    "make_tuned_spikes",
    "make_two_unit_demo",
    "TwoUnitDemo",
]


# ---------------------------------------------------------------------------
# Low-level: bin-wise inhomogeneous Poisson with absolute refractory
# ---------------------------------------------------------------------------


def poisson_train(
    rng: np.random.Generator,
    rate_profile: npt.ArrayLike | float,
    dt: float,
    n_bins: int,
    refractory_s: float = 0.001,
) -> npt.NDArray[np.int64]:
    """Bin-wise inhomogeneous Poisson process with an absolute refractory.

    For each time bin ``b`` of width *dt*, draws a Bernoulli trial
    with probability ``rate(b) · dt``.  After a spike the next
    ``refractory_bins = max(1, int(refractory_s / dt))`` bins cannot
    fire — this is the *absolute* refractory contract, matching the
    convention used by the package's RPV / ACG analyses.

    Args:
        rng: ``numpy.random.Generator`` (or anything with
            ``.uniform()``).  Pass a seeded generator for
            reproducibility.
        rate_profile: Either a scalar (constant rate, Hz) or a
            length-``n_bins`` array of instantaneous rates (Hz).
        dt: Bin width in seconds.
        n_bins: Number of bins to simulate.
        refractory_s: Absolute refractory period in seconds
            (default 1 ms).  Set to 0 to disable.

    Returns:
        ``(n_spikes,)`` array of *bin indices* at which a spike
        fired.  Multiply by *dt* to get times in seconds.

    Notes:
        The implementation is a pure-Python loop because the
        refractory constraint couples consecutive bins; a vectorised
        Bernoulli draw followed by a refractory filter would
        overestimate the spike count whenever two would-be spikes
        fall within the refractory window.  For the typical use
        (25 kHz × 2.5 s × few hundred trials) this finishes in a
        few seconds — fine for one-shot demo construction.
    """
    p_spike = (
        np.asarray(rate_profile, dtype=np.float64) * dt
        if hasattr(rate_profile, "__len__")
        else np.full(n_bins, float(rate_profile) * dt)
    )
    refractory_bins = max(1, int(refractory_s / dt))
    spikes: list[int] = []
    last = -refractory_bins - 1
    for b in range(n_bins):
        if (b - last) > refractory_bins and rng.uniform() < p_spike[b]:
            spikes.append(b)
            last = b
    return np.array(spikes, dtype=np.int64)


# ---------------------------------------------------------------------------
# High-level: single orientation-tuned cluster
# ---------------------------------------------------------------------------


def make_tuned_spikes(
    preferred_angle: float = 90.0,
    n_angles: int = 12,
    n_repeats: int = 20,
    base_rate: float = 2.0,
    peak_rate: float = 30.0,
    sigma_deg: float = 30.0,
    trial_duration: float = 2.5,
    stimulus_onset: float = 0.5,
    rng: np.random.Generator | int | None = None,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Synthetic spike times from a Gaussian-tuned neuron.

    This is the test-friendly variant (``rng.poisson`` + ``rng.uniform``
    per trial) — the binwise refractory-enforcing path lives in
    :func:`make_two_unit_demo` via :func:`poisson_train`.  Keeping
    them separate means seeded test fixtures stay stable when the
    notebook helpers evolve.

    Args:
        preferred_angle: Peak of the Gaussian tuning curve (degrees).
        n_angles: Number of stimulus directions sampled evenly on
            360°.
        n_repeats: Repetitions per angle.
        base_rate: Spontaneous (pre-stimulus) firing rate in Hz.
        peak_rate: Maximum evoked firing rate at the preferred angle.
        sigma_deg: Width of the Gaussian tuning curve (degrees).
        trial_duration: Length of each trial in seconds.
        stimulus_onset: Time inside the trial where the stimulus
            starts (seconds).
        rng: Generator, integer seed, or ``None`` (default: seeded
            at 42 to match the historical fixture behaviour).

    Returns:
        ``(spike_times, trials, angles, unique_angles)``:

        - ``spike_times`` ``(n_spikes,)`` trial-relative times in s
        - ``trials`` ``(n_spikes,)`` 0-based trial index
        - ``angles`` ``(n_trials,)`` stimulus angle per trial
        - ``unique_angles`` ``(n_angles,)`` the distinct directions
    """
    # Default to seed=42 (not OS entropy) so this function reproduces
    # the historical test-fixture stream when called without a seed.
    if rng is None:
        rng = make_rng(42)
    else:
        rng = make_rng(rng)

    angles_deg = np.linspace(0, 360, n_angles, endpoint=False)
    angles = np.repeat(angles_deg, n_repeats)
    n_trials = len(angles)
    stim_duration = trial_duration - stimulus_onset

    all_st: list[npt.NDArray] = []
    all_tr: list[npt.NDArray] = []
    for t_idx in range(n_trials):
        ang = angles[t_idx]
        # Circular distance on the 360° direction circle.
        d = min(abs(ang - preferred_angle), 360 - abs(ang - preferred_angle))
        rate = base_rate + (peak_rate - base_rate) * np.exp(-(d**2) / (2 * sigma_deg**2))
        # Spontaneous (pre-stimulus) spikes.
        n_spont = rng.poisson(base_rate * stimulus_onset)
        spont_times = rng.uniform(0, stimulus_onset, n_spont)
        # Evoked (post-stimulus) spikes.
        n_evoked = rng.poisson(rate * stim_duration)
        evoked_times = rng.uniform(stimulus_onset, trial_duration, n_evoked)
        st = np.sort(np.concatenate([spont_times, evoked_times]))
        all_st.append(st)
        all_tr.append(np.full(len(st), t_idx, dtype=np.int64))

    spike_times = np.concatenate(all_st)
    trials = np.concatenate(all_tr)
    return spike_times, trials, angles, angles_deg


