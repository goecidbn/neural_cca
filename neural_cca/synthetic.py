class TwoUnitDemo(NamedTuple):
    """Bundle of arrays produced by :func:`make_two_unit_demo`.

    Field order matches the variable names the original example
    notebooks used inline, so a notebook cell can do::

        from neural_cca.synthetic import make_two_unit_demo
        demo = make_two_unit_demo(seed=42)
        data = demo.sorting_data

    or unpack the legacy names explicitly when later cells still
    reference them by their old identifiers.

    Attributes:
        spike_times_c1, trials_c1: Cluster 1 (orientation-indifferent).
        spike_times_c2, trials_c2: Cluster 2 (orientation-selective).
        spike_times, trials, waveforms: Merged + chronologically
            sorted arrays — ready to pass to ``load_from_arrays``.
        ground_truth: Cluster ID (0/1) per spike, aligned with
            *spike_times* / *trials* / *waveforms*.
        angles: ``(n_trials,)`` stimulus angle per trial.
        n_trials, n_orientations, n_repeats: Stimulus protocol sizes.
        c2_pref_ori, c2_sigma: Tuning-curve parameters of cluster 2,
            re-exposed so downstream plots can annotate the truth.
        waveform_fs: Sampling rate used to bin the Poisson source
            (also stored on *sorting_data*).
        sorting_data: A fully-loaded :class:`SortingData` container
            equivalent to ``load_from_arrays(...)``.
        rng: The :class:`numpy.random.Generator` used during
            synthesis.  Returned so notebooks that add more noise
            downstream can continue from the same stream.
    """

    spike_times_c1: np.ndarray
    trials_c1: np.ndarray
    spike_times_c2: np.ndarray
    trials_c2: np.ndarray
    spike_times: np.ndarray
    trials: np.ndarray
    waveforms: np.ndarray
    ground_truth: np.ndarray
    angles: np.ndarray
    n_trials: int
    n_orientations: int
    n_repeats: int
    c2_pref_ori: float
    c2_sigma: float
    waveform_fs: float
    sorting_data: SortingData
    rng: np.random.Generator


def make_two_unit_demo(
    seed: np.random.Generator | int | None = 42,
    n_orientations: int = 12,
    n_repeats: int = 20,
    trial_duration: float = 2.5,
    stimulus_onset: float = 0.5,
    waveform_fs: float = 25_000.0,
    baseline_rate: float = 0.5,
    c1_stim_rate: float = 5.0,
    c2_max_rate: float = 10.0,
    c2_sigma: float = 15.0,
    c2_pref_ori: float = 90.0,
    refractory_s: float = 0.001,
    snippet_len: int = 48,
    noise_std: float = 0.3,
) -> TwoUnitDemo:
    """Build the canonical two-cluster spike-sorting demo dataset.

    Two synthetic neurons recorded on the same channel:

    * **Cluster 1** — orientation-indifferent, fires at
      *c1_stim_rate* (Hz) during the stimulus regardless of angle,
      with *baseline_rate* before stimulus onset.
    * **Cluster 2** — orientation-selective with a Gaussian tuning
      curve of width *c2_sigma* centred at *c2_pref_ori*.  Peak rate
      is *c2_max_rate* at the preferred angle, falling off to
      *baseline_rate* far from it.

    Both spike trains come from :func:`poisson_train` (binwise
    inhomogeneous Poisson with an absolute refractory of
    *refractory_s*).  Each cluster gets a Gaussian-template
    waveform plus per-spike Gaussian noise of standard deviation
    *noise_std*.  The two clusters are merged, sorted
    chronologically, and packaged into a :class:`SortingData`
    container so the result can be fed straight into
    :func:`neural_cca.run_sorting_pipeline`.

    Args:
        seed: Integer seed (default 42, matching the original
            notebook), an existing ``Generator``, or ``None`` for OS
            entropy.
        n_orientations: Number of distinct stimulus directions
            sampled evenly across 360°.
        n_repeats: Trials per direction.
        trial_duration: Length of each trial (seconds).  The stimulus
            occupies ``[stimulus_onset, trial_duration]``.
        stimulus_onset: When the stimulus turns on within a trial
            (seconds).
        waveform_fs: Sampling rate used both for the binwise Poisson
            and for the waveform x-axis (Hz).  25 kHz → 0.04 ms bins.
        baseline_rate, c1_stim_rate, c2_max_rate, c2_sigma,
            c2_pref_ori: Tuning-curve parameters (see docstring intro).
        refractory_s: Absolute refractory used by
            :func:`poisson_train` (seconds).
        snippet_len: Length of each waveform snippet (samples).
        noise_std: Per-sample Gaussian noise added to the waveform
            templates.

    Returns:
        :class:`TwoUnitDemo` — every array the example notebooks need.
    """
    rng = make_rng(seed)

    # ---- Stimulus protocol --------------------------------------
    n_trials = n_orientations * n_repeats
    angles_map = steps2degree(n_orientations)
    angles = np.array(
        [angles_map[(i % n_orientations) + 1] for i in range(n_trials)],
        dtype=np.float64,
    )

    # ---- Timing -------------------------------------------------
    dt = 1.0 / float(waveform_fs)
    n_bins = int(trial_duration / dt)
    time_axis = np.arange(n_bins) * dt
    pre_stim = time_axis < stimulus_onset

    # ---- Cluster 1: orientation-indifferent ---------------------
    spike_times_c1_list: list[np.ndarray] = []
    trials_c1_list: list[np.ndarray] = []
    for trial_idx in range(n_trials):
        rate = np.where(pre_stim, baseline_rate, c1_stim_rate)
        bins_fired = poisson_train(rng, rate, dt, n_bins, refractory_s=refractory_s)
        spike_times_c1_list.append(bins_fired * dt)
        trials_c1_list.append(np.full(len(bins_fired), trial_idx, dtype=np.int64))
    spike_times_c1 = np.concatenate(spike_times_c1_list)
    trials_c1 = np.concatenate(trials_c1_list)

    # ---- Cluster 2: orientation-selective -----------------------
    spike_times_c2_list: list[np.ndarray] = []
    trials_c2_list: list[np.ndarray] = []
    for trial_idx in range(n_trials):
        ori = angles[trial_idx]
        # Wrap to [0, 180) for orientation distance (period 180°).
        ori_diff = abs(ori - c2_pref_ori) % 180
        ori_diff = min(ori_diff, 180 - ori_diff)
        stim_rate = c2_max_rate * np.exp(-(ori_diff**2) / (2 * c2_sigma**2))
        rate = np.where(pre_stim, baseline_rate, stim_rate)
        bins_fired = poisson_train(rng, rate, dt, n_bins, refractory_s=refractory_s)
        spike_times_c2_list.append(bins_fired * dt)
        trials_c2_list.append(np.full(len(bins_fired), trial_idx, dtype=np.int64))
    spike_times_c2 = np.concatenate(spike_times_c2_list)
    trials_c2 = np.concatenate(trials_c2_list)

    # ---- Waveform snippets --------------------------------------
    t_wv = np.linspace(0, 1, snippet_len)
    # Cluster 1 template: sharp negative peak around sample 30 %.
    template_c1 = -4.0 * np.exp(-((t_wv - 0.3) ** 2) / 0.005)
    # Cluster 2 template: broader positive peak around sample 40 %.
    template_c2 = 2.0 * np.exp(-((t_wv - 0.4) ** 2) / 0.02)
    wv_c1 = template_c1[np.newaxis, :] + rng.normal(
        0.0, noise_std, (len(spike_times_c1), snippet_len)
    )
    wv_c2 = template_c2[np.newaxis, :] + rng.normal(
        0.0, noise_std, (len(spike_times_c2), snippet_len)
    )

    # ---- Merge + chronological sort -----------------------------
    spike_times = np.concatenate([spike_times_c1, spike_times_c2])
    trials = np.concatenate([trials_c1, trials_c2])
    waveforms = np.vstack([wv_c1, wv_c2])
    ground_truth = np.concatenate(
        [
            np.zeros(len(spike_times_c1), dtype=np.int64),
            np.ones(len(spike_times_c2), dtype=np.int64),
        ]
    )
    sort_idx = np.argsort(spike_times)
    spike_times = spike_times[sort_idx]
    trials = trials[sort_idx]
    waveforms = waveforms[sort_idx]
    ground_truth = ground_truth[sort_idx]

    sorting_data = load_from_arrays(
        waveforms=waveforms,
        spike_times=spike_times,
        trials=trials,
        angles=angles,
        waveform_fs=waveform_fs,
        stim_window=(stimulus_onset, trial_duration),
    )

    return TwoUnitDemo(
        spike_times_c1=spike_times_c1,
        trials_c1=trials_c1,
        spike_times_c2=spike_times_c2,
        trials_c2=trials_c2,
        spike_times=spike_times,
        trials=trials,
        waveforms=waveforms,
        ground_truth=ground_truth,
        angles=angles,
        n_trials=n_trials,
        n_orientations=n_orientations,
        n_repeats=n_repeats,
        c2_pref_ori=c2_pref_ori,
        c2_sigma=c2_sigma,
        waveform_fs=waveform_fs,
        sorting_data=sorting_data,
        rng=rng,
    )
